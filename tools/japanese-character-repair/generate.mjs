import { createHash } from "node:crypto";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { ConverterFactory } from "opencc-js/core";
import JapaneseShinjitaiCharacters from "opencc-js/dict/JPShinjitaiCharactersRev";
import SimplifiedToTraditionalCharacters from "opencc-js/dict/STCharacters";

const [, , dictionaryDirectoryArgument, properNameDirectoryArgument, outputArgument] =
  process.argv;
if (!dictionaryDirectoryArgument || !properNameDirectoryArgument) {
  throw new Error(
    "Usage: node tools/japanese-character-repair/generate.mjs <JMdict Yomitan directory> <JMnedict Yomitan directory> [output]",
  );
}

const dictionaryDirectory = resolve(dictionaryDirectoryArgument);
const properNameDirectory = resolve(properNameDirectoryArgument);
const outputPath = resolve(
  outputArgument ??
    "src/utils/Lyrics/Processing/Japanese/ChineseProviderCharacterMap.generated.ts",
);
function loadYomitanHeadwordCharacters(directory) {
  const index = JSON.parse(readFileSync(resolve(directory, "index.json"), "utf8"));
  const termBankFiles = readdirSync(directory)
    .filter((name) => /^term_bank_\d+\.json$/u.test(name))
    .sort((left, right) => {
      const number = (name) => Number(name.match(/\d+/u)?.[0] ?? 0);
      return number(left) - number(right);
    });
  const headwordCharacters = new Set();
  for (const file of termBankFiles) {
    const entries = JSON.parse(readFileSync(resolve(directory, file), "utf8"));
    for (const entry of entries) {
      for (const character of entry[0] ?? "") headwordCharacters.add(character);
    }
  }
  return {
    headwordCharacters,
    revision: String(index.revision ?? index.title ?? "unknown"),
    termBankCount: termBankFiles.length,
  };
}

const lexicalDictionary = loadYomitanHeadwordCharacters(dictionaryDirectory);
const properNameDictionary = loadYomitanHeadwordCharacters(properNameDirectory);
const broadConverter = ConverterFactory(
  [SimplifiedToTraditionalCharacters],
  [JapaneseShinjitaiCharacters],
);
const simplifiedToTraditionalConverter = ConverterFactory(
  [SimplifiedToTraditionalCharacters],
);
const mappings = [];
let broadChangedCodePoints = 0;
for (let codePoint = 0x3400; codePoint <= 0x9fff; codePoint += 1) {
  const source = String.fromCodePoint(codePoint);
  const target = broadConverter(source);
  if (source === target) continue;
  broadChangedCodePoints += 1;
  if (
    simplifiedToTraditionalConverter(source) !== source &&
    Array.from(target).length === 1 &&
    source.length === target.length &&
    !lexicalDictionary.headwordCharacters.has(source) &&
    !properNameDictionary.headwordCharacters.has(source) &&
    lexicalDictionary.headwordCharacters.has(target)
  ) {
    mappings.push([source, target]);
  }
}

const sources = mappings.map(([source]) => source).join("");
const targets = mappings.map(([, target]) => target).join("");
const mappingSha256 = createHash("sha256")
  .update(`${sources}\0${targets}`, "utf8")
  .digest("hex")
  .toUpperCase();
const generated = `// Generated by tools/japanese-character-repair/generate.mjs.
// Sources: opencc-js 1.4.0 character dictionaries, ${lexicalDictionary.revision}, and ${properNameDictionary.revision}.
// JMdict and JMnedict material is used under the EDRDG licence:
// https://www.edrdg.org/wiki/index.php/JMdict-EDICT_Dictionary_Project

export const CHINESE_PROVIDER_CHARACTER_MAP_METADATA = Object.freeze({
  sourceRevision: ${JSON.stringify(lexicalDictionary.revision)},
  properNameSourceRevision: ${JSON.stringify(properNameDictionary.revision)},
  broadChangedCodePoints: ${broadChangedCodePoints},
  mappingCount: ${mappings.length},
  mappingSha256: ${JSON.stringify(mappingSha256)},
});

const SOURCES = ${JSON.stringify(sources)};
const TARGETS = ${JSON.stringify(targets)};
const targetCharacters = Array.from(TARGETS);

export const CHINESE_PROVIDER_JAPANESE_CHARACTER_PATTERN = new RegExp(\`[\${SOURCES}]\`, "gu");

export const CHINESE_PROVIDER_JAPANESE_CHARACTER_MAP = new Map(
  Array.from(SOURCES, (source, index) => [source, targetCharacters[index]] as const),
);
`;

writeFileSync(outputPath, generated, "utf8");
console.log(
  JSON.stringify({
    outputPath,
    revision: lexicalDictionary.revision,
    properNameRevision: properNameDictionary.revision,
    termBanks: lexicalDictionary.termBankCount,
    properNameTermBanks: properNameDictionary.termBankCount,
    broadChangedCodePoints,
    mappingCount: mappings.length,
    mappingSha256,
  }),
);
